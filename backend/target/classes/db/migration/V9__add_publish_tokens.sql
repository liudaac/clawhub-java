CREATE TABLE skill_publish_tokens (
    id BIGINT PRIMARY KEY AUTO_INCREMENT,
    skill_id VARCHAR(36) NOT NULL,
    version VARCHAR(50),
    token_hash VARCHAR(255) NOT NULL,
    provider VARCHAR(50) NOT NULL DEFAULT 'github-actions',
    repository VARCHAR(255) NOT NULL,
    repository_id VARCHAR(50) NOT NULL,
    repository_owner VARCHAR(100) NOT NULL,
    repository_owner_id VARCHAR(50) NOT NULL,
    workflow_filename VARCHAR(255) NOT NULL,
    environment VARCHAR(100) NOT NULL,
    run_id VARCHAR(50) NOT NULL,
    run_attempt VARCHAR(10) NOT NULL,
    sha VARCHAR(100) NOT NULL,
    ref VARCHAR(255) NOT NULL,
    ref_type VARCHAR(50),
    actor VARCHAR(100),
    actor_id VARCHAR(50),
    expires_at TIMESTAMP NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    last_used_at TIMESTAMP,
    revoked_at TIMESTAMP,
    FOREIGN KEY (skill_id) REFERENCES skills(id) ON DELETE CASCADE,
    INDEX idx_publish_token_hash (token_hash),
    INDEX idx_publish_token_expires (expires_at),
    INDEX idx_publish_token_skill (skill_id)
);
